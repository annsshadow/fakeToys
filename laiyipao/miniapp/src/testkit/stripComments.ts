/**
 * 测试用的源码文本工具。
 *
 * # 为什么要有这个模块
 *
 * 「扫源码」的守卫必须先**剥掉注释**，否则它会在注释里找到目标。
 * 这个坑在同一个项目里踩了**四次**：
 *
 * | 轮 | 现象 |
 * |---|---|
 * | 第 83 轮 | `canvas.ts` 的说明注释里两次提到 `spec.aoeRadius`，于是「没人读它」那条守卫误报 |
 * | 第 88 轮 | 修复说明里引用了「修复前的写法」，判据在注释里找到目标 → **变异全绿** |
 * | 第 94 轮 | 说明注释里写着 ``fetchTasks('daily')``，「不得硬编码」那条守卫误报 |
 * | 第 83 轮 | 守卫正文里的示例字面量被扫成数据 |
 *
 * 四次的**根因是同一个**：每次都在新测试文件里重写判据，
 * 于是「剥注释」被**重写了三次**而不是共用一次。
 * 每一份重写都只覆盖了当时遇到的那一种注释形式。
 *
 * > 消除重复时只改了自己看见的那一处，等于没消除。
 * > —— 与 `admin/src/reactions.ts` 的注释是同一条教训，
 * > 那条也是「只在注意到气味的那个页面上找」。
 *
 * # 三种注释形式都要覆盖
 *
 * 1. `// …` 行注释
 * 2. C 风格的块注释（斜杠 + 星号 … 星号 + 斜杠）
 * 3. `<!-- … -->` **模板里的 HTML 注释**（`.vue` 的 `<template>` 段落）
 *
 * ⚠️ 缺任何一种，就会出现「判据在读注释」的**假阴性** ——
 * 而假阴性不会以任何形式暴露自己：守卫只是**莫名其妙地绿**。
 *
 * # 取舍：这是**文本级**剥离，不是 AST
 *
 * 它对字符串字面量里的 `//` 会误伤。
 *
 * 会不会出问题？只有当某个字符串字面量里恰好含有
 * 「两个斜杠紧跟 spec.aoeRadius」这类文本时才会误判，而那种写法本身就可疑。
 *
 * 真正的解析器（`ts.createSourceFile`）更准，但引入编译器依赖
 * 只为几条守卫不值 —— **误伤的代价是「有人要来解释这条为什么红了」**。
 * 这个取舍写在这里，而不是留给后来的人猜。
 */
//
// ⚠️ 本文件的文档注释里**不能**出现块注释的结束符字面量 ——
// 它会提前闭合注释，剩下的内容被当成代码，编译报
// `TS1127: Invalid character`。我写第一版时就踩了：
// 为了说明「有哪几种注释形式」而列了 `/* … */`，结果就是它自己。
// 描述「结束符」而不写出它。

export function stripTsComments(src: string): string {
  return (
    src
      .replace(/\/\*[\s\S]*?\*\//g, ' ')
      .replace(/^\s*\/\/.*$/gm, ' ')
      .replace(/<!--[\s\S]*?-->/g, ' ')
  )
}

/**
 * 读一个源码文件并**剥掉注释**。
 *
 * 绝大多数「扫源码」守卫都应该用这个而不是裸 `readFileSync` ——
 * 裸读的那份会在注释里找到目标，而那不会报错。
 */
export function readSourceStripped(path: string): string {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  const { readFileSync } = require('node:fs') as typeof import('node:fs')
  return stripTsComments(readFileSync(path, 'utf-8'))
}