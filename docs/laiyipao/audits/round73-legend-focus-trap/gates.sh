#!/bin/bash
set -uo pipefail
ROOT="$(pwd)"
OUT="$ROOT/docs/laiyipao/audits/round73-legend-focus-trap/data/gates-out.txt"
: > "$OUT"
cd "$ROOT/laiyipao/miniapp"
echo "===== G1 契约 r73LegendFocus =====" >> "$OUT"
pnpm exec vitest run src/styles/r73LegendFocus.contract.test.ts --reporter=verbose >> "$OUT" 2>&1; echo "G1_RC=$?" >> "$OUT"
echo "===== G2 battle.test =====" >> "$OUT"
pnpm exec vitest run src/pages/battle/battle.test.ts --reporter=verbose >> "$OUT" 2>&1; echo "G2_RC=$?" >> "$OUT"
echo "===== G3 全量 vitest =====" >> "$OUT"
pnpm exec vitest run --reporter=verbose >> "$OUT" 2>&1; echo "G3_RC=$?" >> "$OUT"
echo "===== G4 vue-tsc =====" >> "$OUT"
pnpm exec vue-tsc --noEmit >> "$OUT" 2>&1; echo "G4_RC=$?" >> "$OUT"
echo "===== G5 build:h5 =====" >> "$OUT"
pnpm run build:h5 >> "$OUT" 2>&1; echo "G5_RC=$?" >> "$OUT"
cd "$ROOT"
echo "===== G6 git diff --check =====" >> "$OUT"
git diff --check >> "$OUT" 2>&1; echo "G6_RC=$?" >> "$OUT"
echo GATES_ALL_DONE >> "$OUT"
