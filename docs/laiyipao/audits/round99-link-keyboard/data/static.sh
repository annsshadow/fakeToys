#!/bin/bash
ROOT="$(pwd)"
OUT="$ROOT/docs/laiyipao/audits/round99-link-keyboard/data/static-out.txt"
: > "$OUT"
echo "=== TOKENS ===" >> "$OUT"
grep -nE "--(accent|ice|bad):" "$ROOT/laiyipao/miniapp/src/styles/tokens.css" | head -8 >> "$OUT"
echo "=== R99 CONTRACT CASES ===" >> "$OUT"
grep -nE "role=|tabindex=\"0\"|keydown.enter" "$ROOT/laiyipao/miniapp/src/styles/r99LinkKeyboard.contract.test.ts" | head -12 >> "$OUT"
echo "=== BUSINESS --r99- (expect NO) ===" >> "$OUT"
grep -rn -- "--r99-" "$ROOT/laiyipao/miniapp/src" --include="*.vue" --include="*.css" || echo NO_MATCH >> "$OUT"
echo "=== DISABLED STATIC ===" >> "$OUT"
grep -nE "resetMastery|doBuy" "$ROOT/laiyipao/miniapp/src/pages/mastery/mastery.vue" "$ROOT/laiyipao/miniapp/src/pages/shop/shop.vue" | head -10 >> "$OUT"
echo "=== GIT ===" >> "$OUT"
git -C "$ROOT" status --porcelain | grep -v "^??" >> "$OUT"
git -C "$ROOT" rev-parse HEAD >> "$OUT"
echo STATIC_DONE >> "$OUT"
