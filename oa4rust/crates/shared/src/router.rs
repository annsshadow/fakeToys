use axum::routing::get;
use axum::Router;

// ──────────────────────────────────────────────────────────────────────────────
// router
//
// 提供当前服务的业务路由（无中间件）。
//
// 路由结构：
//   GET /health  → 健康检查端点，返回 "ok"
//
// 认证/授权/限流/安全头中间件由 main.rs 在顶层统一挂载一次
// （SecurityState 单一实例），确保所有 /jaxrs/* 路由都经过认证，
// 避免各 crate router 各自挂载造成的重复或遗漏。
// ──────────────────────────────────────────────────────────────────────────────
pub fn router() -> Router {
    Router::new().route("/health", get(|| async { "ok" }))
}
